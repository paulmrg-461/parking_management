create or replace function public.revoke_merchant_validation(
    p_id bigint,
    p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    lot integer := public.require_lot_admin();
    validation public.merchant_validations%rowtype;
    reason text := btrim(coalesce(p_reason, ''));
    session public.parking_sessions%rowtype;
begin
    select * into validation
      from public.merchant_validations v
     where v.id = p_id and v.lot_id = lot;
    if not found then
        raise exception 'ValidationNotFoundError';
    end if;
    if length(reason) < 3 or length(reason) > 200 then
        raise exception 'RevokeReasonRequiredError';
    end if;
    select * into session from public.parking_sessions s where s.id = validation.session_id;
    if validation.status <> 'pending' or session.status <> 'open' then
        raise exception 'ValidationNotRevocableError';
    end if;

    update public.merchant_validations
       set status = 'revoked',
           revoked_by = public.current_app_user_id(),
           revoked_at = now(),
           revoke_reason = reason
     where id = validation.id;

    return jsonb_build_object('id', validation.id, 'status', 'revoked');
end;
$$;

