create or replace function public.save_merchant(
    p_name text,
    p_benefit_kind text,
    p_benefit_value integer,
    p_max_amount integer,
    p_billing_mode text,
    p_daily_cap integer,
    p_monthly_cap integer,
    p_active boolean,
    p_id integer default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    lot integer := public.require_lot_admin();
    clean_name text := btrim(coalesce(p_name, ''));
    kind text := nullif(btrim(coalesce(p_benefit_kind, '')), '');
    mode_value text := coalesce(nullif(btrim(coalesce(p_billing_mode, '')), ''), 'merchant_paid');
    merchant_id integer;
    credentials jsonb;
begin
    if length(clean_name) < 2 or length(clean_name) > 120 then
        raise exception 'InvalidDataError';
    end if;
    if kind not in ('free_minutes', 'percentage', 'fixed_amount') then
        raise exception 'InvalidDataError';
    end if;
    if (kind = 'free_minutes' and p_benefit_value not between 1 and 1440)
       or (kind = 'percentage' and p_benefit_value not between 1 and 100)
       or (kind = 'fixed_amount' and coalesce(p_benefit_value, 0) < 1) then
        raise exception 'InvalidDataError';
    end if;
    if p_max_amount is not null and p_max_amount <= 0 then
        raise exception 'InvalidDataError';
    end if;
    if mode_value not in ('merchant_paid', 'courtesy') then
        raise exception 'InvalidDataError';
    end if;
    if p_daily_cap is not null and p_daily_cap not between 1 and 10000 then
        raise exception 'InvalidDataError';
    end if;
    if p_monthly_cap is not null and p_monthly_cap not between 1 and 100000 then
        raise exception 'InvalidDataError';
    end if;

    if p_id is null then
        begin
            insert into public.merchants (
                lot_id, name, benefit_kind, benefit_value, max_amount,
                billing_mode, daily_cap, monthly_cap, active
            )
            values (
                lot, clean_name, kind, p_benefit_value, p_max_amount,
                mode_value, p_daily_cap, p_monthly_cap, coalesce(p_active, true)
            )
            returning id into merchant_id;
        exception when unique_violation then
            raise exception 'DuplicateMerchantError';
        end;
        credentials := public.rotate_merchant_credentials(merchant_id, true);
        return jsonb_build_object(
            'merchant', public.merchant_summary(merchant_id),
            'credentials', jsonb_build_object(
                'token', credentials ->> 'token',
                'pin', credentials ->> 'pin',
                'link_path', credentials ->> 'link_path'
            )
        );
    end if;

    begin
        update public.merchants
           set name = clean_name,
               benefit_kind = kind,
               benefit_value = p_benefit_value,
               max_amount = p_max_amount,
               billing_mode = mode_value,
               daily_cap = p_daily_cap,
               monthly_cap = p_monthly_cap,
               active = coalesce(p_active, true),
               updated_at = now()
         where id = p_id and lot_id = lot
         returning id into merchant_id;
    exception when unique_violation then
        raise exception 'DuplicateMerchantError';
    end;
    if merchant_id is null then
        raise exception 'MerchantNotFoundError';
    end if;

    return jsonb_build_object(
        'merchant', public.merchant_summary(merchant_id),
        'credentials', null
    );
end;
$$;

revoke all on function public.save_merchant(text, text, integer, integer, text, integer, integer, boolean, integer)
    from public;
grant execute on function public.save_merchant(text, text, integer, integer, text, integer, integer, boolean, integer)
    to authenticated;

