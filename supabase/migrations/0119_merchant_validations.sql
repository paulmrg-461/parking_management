-- Merchant agreements — RPCs, the public validation page and the consumers of
-- `fare_quote` (check-out, preview, public summary, history, anomaly rule).
--
-- Credentials model: `merchants` is audited and readable by the lot staff;
-- `merchant_credentials` (token hash + bcrypt PIN hash) has RLS with no policy
-- and no grant, and only these security-definer functions touch it. A wrong
-- PIN returns JSON instead of raising, so the attempt counter is committed.

-- ---------------------------------------------------------------------------
-- Helpers.
-- ---------------------------------------------------------------------------
create or replace function public.merchant_hash_token(p_token text)
returns text
language sql
immutable
set search_path = public, extensions
as $$
    select encode(digest(coalesce(p_token, ''), 'sha256'), 'hex');
$$;

revoke all on function public.merchant_hash_token(text)
    from public, anon, authenticated;

create or replace function public.merchant_summary(p_merchant_id integer)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
    with m as (
        select * from public.merchants where id = p_merchant_id
    ), tz as (
        select coalesce(ps.business_timezone, 'America/Bogota') as name
          from public.parking_settings ps
          join m on m.lot_id = ps.lot_id
    )
    select jsonb_build_object(
        'id', m.id,
        'name', m.name,
        'benefit_kind', m.benefit_kind,
        'benefit_value', m.benefit_value,
        'max_amount', m.max_amount,
        'billing_mode', m.billing_mode,
        'daily_cap', m.daily_cap,
        'monthly_cap', m.monthly_cap,
        'active', m.active,
        'used_today', (
            select count(*) from public.merchant_validations v
             where v.merchant_id = m.id
               and v.status <> 'revoked'
               and (v.created_at at time zone tz.name)::date =
                   (now() at time zone tz.name)::date
        ),
        'used_month', (
            select count(*) from public.merchant_validations v
             where v.merchant_id = m.id
               and v.status <> 'revoked'
               and date_trunc('month', v.created_at at time zone tz.name) =
                   date_trunc('month', now() at time zone tz.name)
        ),
        'pending_now', (
            select count(*) from public.merchant_validations v
             where v.merchant_id = m.id and v.status = 'pending'
        ),
        'locked', coalesce((
            select c.locked_until > now()
              from public.merchant_credentials c
             where c.merchant_id = m.id
        ), false),
        'credentials_version', m.credentials_version,
        'created_at', m.created_at
    )
      from m, tz;
$$;

revoke all on function public.merchant_summary(integer)
    from public, anon, authenticated;

create or replace function public.rotate_merchant_credentials(
    p_merchant_id integer,
    p_rotate_token boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    bytes bytea := gen_random_bytes(4);
    new_pin text;
    new_token text;
    has_row boolean;
    generated boolean := false;
begin
    select exists (
        select 1 from public.merchant_credentials c
         where c.merchant_id = p_merchant_id
    ) into has_row;

    -- A 6-digit PIN generated by the server (the admin never chooses it).
    new_pin := lpad((
        (
            get_byte(bytes, 0)::bigint * 16777216 +
            get_byte(bytes, 1)::bigint * 65536 +
            get_byte(bytes, 2)::bigint * 256 +
            get_byte(bytes, 3)::bigint
        ) % 1000000
    )::text, 6, '0');

    if not has_row or coalesce(p_rotate_token, false) then
        new_token := encode(gen_random_bytes(24), 'hex');
        generated := true;
        insert into public.merchant_credentials (
            merchant_id, token_hash, pin_hash, pin_failures, locked_until,
            token_rotated_at, pin_set_at
        )
        values (
            p_merchant_id,
            public.merchant_hash_token(new_token),
            crypt(new_pin, gen_salt('bf', 8)),
            0,
            null,
            now(),
            now()
        )
        on conflict (merchant_id) do update
            set token_hash = excluded.token_hash,
                token_rotated_at = now(),
                pin_hash = excluded.pin_hash,
                pin_failures = 0,
                locked_until = null,
                pin_set_at = now();
    else
        update public.merchant_credentials
           set pin_hash = crypt(new_pin, gen_salt('bf', 8)),
               pin_failures = 0,
               locked_until = null,
               pin_set_at = now()
         where merchant_id = p_merchant_id;
    end if;

    return jsonb_build_object(
        'pin', new_pin,
        'token', new_token,
        'link_path', case when generated then '/validate?m=' || new_token end
    );
end;
$$;

revoke all on function public.rotate_merchant_credentials(integer, boolean)
    from public, anon, authenticated;

