create or replace function public.merchant_validate(
    p_token text,
    p_pin text,
    p_plate text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    hashed_token text := public.merchant_hash_token(btrim(coalesce(p_token, '')));
    merchant public.merchants%rowtype;
    credentials public.merchant_credentials%rowtype;
    failures integer;
    normalized text := upper(regexp_replace(coalesce(p_plate, ''), '\s', '', 'g'));
    session_id integer;
    correct boolean;
begin
    select m.* into merchant
      from public.merchant_credentials c
      join public.merchants m on m.id = c.merchant_id
     where c.token_hash = hashed_token
       and m.active;
    if not found then
        raise exception 'MerchantNotFoundError';
    end if;

    perform pg_advisory_xact_lock(hashtext('merchant_pin'), merchant.id);

    select * into credentials
      from public.merchant_credentials c
     where c.merchant_id = merchant.id
     for update;
    if not found then
        raise exception 'MerchantNotFoundError';
    end if;

    if credentials.locked_until is not null and credentials.locked_until > now() then
        return jsonb_build_object(
            'status', 'locked',
            'locked_until', credentials.locked_until
        );
    end if;

    -- A wrong PIN must not raise: the counter has to survive the request.
    correct := coalesce(p_pin ~ '^[0-9]{6}$', false)
        and crypt(p_pin, credentials.pin_hash) = credentials.pin_hash;

    if not correct then
        failures := credentials.pin_failures + 1;
        if failures >= 5 then
            update public.merchant_credentials
               set pin_failures = 0,
                   locked_until = now() + interval '15 minutes'
             where merchant_id = merchant.id;
            return jsonb_build_object(
                'status', 'locked',
                'locked_until', now() + interval '15 minutes'
            );
        end if;
        update public.merchant_credentials
           set pin_failures = failures
         where merchant_id = merchant.id;
        return jsonb_build_object(
            'status', 'invalid_pin',
            'attempts_left', 5 - failures
        );
    end if;

    update public.merchant_credentials
       set pin_failures = 0, last_used_at = now()
     where merchant_id = merchant.id;

    if normalized !~ '^[A-Z0-9-]{3,20}$' then
        raise exception 'InvalidPlateError';
    end if;

    select s.id into session_id
      from public.parking_sessions s
      join public.vehicles v on v.id = s.vehicle_id
     where s.status = 'open'
       and s.lot_id = merchant.lot_id
       and upper(regexp_replace(v.plate, '\s', '', 'g')) = normalized
     order by s.entry_time desc
     limit 1;
    if session_id is null then
        raise exception 'SessionNotFoundError';
    end if;

    perform public.create_merchant_validation(
        merchant.id, session_id, 'public', null
    );

    return jsonb_build_object(
        'status', 'registered',
        'merchant_name', merchant.name,
        'benefit_kind', merchant.benefit_kind,
        'benefit_value', merchant.benefit_value,
        'max_amount', merchant.max_amount
    );
end;
$$;

revoke all on function public.merchant_validate(text, text, text) from public;
grant execute on function public.merchant_validate(text, text, text)
    to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Settlement report.
-- ---------------------------------------------------------------------------
create or replace function public.report_merchant_settlement(
    p_start_date date,
    p_end_date date
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    lot integer := public.current_lot_id();
    tz text;
    window_start timestamptz;
    window_end timestamptz;
    stats jsonb;
    totals jsonb;
begin
    perform public.require_admin();
    if p_start_date is null or p_end_date is null or p_start_date > p_end_date then
        raise exception 'InvalidReportRangeError';
    end if;

    select coalesce(business_timezone, 'America/Bogota') into tz
      from public.parking_settings where lot_id = lot;
    tz := coalesce(tz, 'America/Bogota');
    window_start := p_start_date::timestamp at time zone tz;
    window_end := (p_end_date + 1)::timestamp at time zone tz;

    with per_merchant as (
        select m.id,
               m.name,
               m.billing_mode,
               m.benefit_kind,
               count(v.id) filter (
                   where v.created_at >= window_start and v.created_at < window_end
               ) as validations,
               count(v.id) filter (
                   where v.status = 'applied'
                     and v.applied_at >= window_start and v.applied_at < window_end
               ) as applied,
               count(v.id) filter (
                   where v.status = 'forfeited'
                     and v.applied_at >= window_start and v.applied_at < window_end
               ) as forfeited,
               count(v.id) filter (
                   where v.status = 'revoked'
                     and v.revoked_at >= window_start and v.revoked_at < window_end
               ) as revoked,
               count(v.id) filter (where v.status = 'pending') as pending_now,
               coalesce(sum(v.amount) filter (
                   where v.status = 'applied'
                     and v.applied_at >= window_start and v.applied_at < window_end
               ), 0) as discounted_amount,
               coalesce(sum(v.amount) filter (
                   where v.status = 'applied'
                     and v.applied_at >= window_start and v.applied_at < window_end
                     and v.terms ->> 'billing_mode' = 'merchant_paid'
               ), 0) as amount_owed,
               coalesce(sum(v.amount) filter (
                   where v.status = 'applied'
                     and v.applied_at >= window_start and v.applied_at < window_end
                     and v.terms ->> 'billing_mode' = 'courtesy'
               ), 0) as courtesy_amount
          from public.merchants m
          left join public.merchant_validations v on v.merchant_id = m.id
         where m.lot_id = lot
         group by m.id, m.name, m.billing_mode, m.benefit_kind
    )
    select coalesce(jsonb_agg(jsonb_build_object(
               'merchant_id', pm.id,
               'name', pm.name,
               'billing_mode', pm.billing_mode,
               'benefit_kind', pm.benefit_kind,
               'validations', pm.validations,
               'applied', pm.applied,
               'forfeited', pm.forfeited,
               'revoked', pm.revoked,
               'pending_now', pm.pending_now,
               'discounted_amount', pm.discounted_amount,
               'amount_owed', pm.amount_owed,
               'courtesy_amount', pm.courtesy_amount
           ) order by pm.name), '[]'::jsonb),
           jsonb_build_object(
               'validations', coalesce(sum(pm.validations), 0),
               'applied', coalesce(sum(pm.applied), 0),
               'forfeited', coalesce(sum(pm.forfeited), 0),
               'revoked', coalesce(sum(pm.revoked), 0),
               'discounted_amount', coalesce(sum(pm.discounted_amount), 0),
               'amount_owed', coalesce(sum(pm.amount_owed), 0),
               'courtesy_amount', coalesce(sum(pm.courtesy_amount), 0)
           )
      into stats, totals
      from per_merchant pm;

    return jsonb_build_object(
        'from', p_start_date,
        'to', p_end_date,
        'merchants', stats,
        'totals', totals
    );
end;
$$;

