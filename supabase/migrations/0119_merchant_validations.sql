-- ---------------------------------------------------------------------------
-- Validations (desk, public, revoke).
-- ---------------------------------------------------------------------------
create or replace function public.create_merchant_validation(
    p_merchant_id integer,
    p_session_id integer,
    p_source text,
    p_actor integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    merchant public.merchants%rowtype;
    session public.parking_sessions%rowtype;
    settings public.parking_settings%rowtype;
    tz text;
    already integer;
    per_session integer;
    used_today integer;
    used_month integer;
    validation_id bigint;
    terms jsonb;
begin
    perform pg_advisory_xact_lock(hashtext('merchant_validation'), p_merchant_id);

    select * into merchant from public.merchants m where m.id = p_merchant_id;
    if not found then
        raise exception 'MerchantNotFoundError';
    end if;
    if not merchant.active then
        raise exception 'MerchantInactiveError';
    end if;

    select * into session
      from public.parking_sessions s
     where s.id = p_session_id
     for share;
    if not found or session.status <> 'open' or session.lot_id <> merchant.lot_id then
        raise exception 'SessionNotFoundError';
    end if;

    select * into settings from public.parking_settings ps where ps.lot_id = merchant.lot_id;
    tz := coalesce(settings.business_timezone, 'America/Bogota');

    if exists (
        select 1 from public.monthly_passes mp
         where mp.vehicle_id = session.vehicle_id
           and mp.lot_id = session.lot_id
           and mp.active
           and mp.start_date <= (now() at time zone tz)::date
           and mp.end_date >= (now() at time zone tz)::date
    ) then
        raise exception 'SessionNotEligibleError';
    end if;

    if exists (
        select 1 from public.merchant_validations v
         where v.merchant_id = merchant.id
           and v.session_id = session.id
           and v.status <> 'revoked'
    ) then
        raise exception 'AlreadyValidatedError';
    end if;

    select count(*) into per_session
      from public.merchant_validations v
     where v.session_id = session.id and v.status <> 'revoked';
    if per_session >= coalesce(settings.merchant_max_per_session, 0) then
        raise exception 'MerchantLimitError';
    end if;

    select count(*) filter (
               where (v.created_at at time zone tz)::date = (now() at time zone tz)::date
           ),
           count(*) filter (
               where date_trunc('month', v.created_at at time zone tz) =
                     date_trunc('month', now() at time zone tz)
           )
      into used_today, used_month
      from public.merchant_validations v
     where v.merchant_id = merchant.id and v.status <> 'revoked';
    if merchant.daily_cap is not null and used_today >= merchant.daily_cap then
        raise exception 'MerchantCapError';
    end if;
    if merchant.monthly_cap is not null and used_month >= merchant.monthly_cap then
        raise exception 'MerchantCapError';
    end if;

    terms := jsonb_build_object(
        'merchant_name', merchant.name,
        'benefit_kind', merchant.benefit_kind,
        'benefit_value', merchant.benefit_value,
        'max_amount', merchant.max_amount,
        'billing_mode', merchant.billing_mode
    );

    insert into public.merchant_validations (
        lot_id, merchant_id, session_id, source, created_by, status, terms
    )
    values (
        merchant.lot_id, merchant.id, session.id, p_source, p_actor, 'pending', terms
    )
    returning id into validation_id;

    return jsonb_build_object(
        'validation_id', validation_id,
        'merchant_id', merchant.id,
        'merchant_name', merchant.name,
        'status', 'pending'
    );
end;
$$;

revoke all on function public.create_merchant_validation(integer, integer, text, integer)
    from public, anon, authenticated;

create or replace function public.add_merchant_validation(
    p_merchant_id integer,
    p_session_id integer
)
returns jsonb
language plpgsql
